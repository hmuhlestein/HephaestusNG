#!/usr/bin/env python3
"""Fetch Anthropic model pricing and update cost_collection_service.py.

Sources (tried in order):
1. Anthropic API /models endpoint (requires ANTHROPIC_API_KEY)
2. OpenRouter API (public, but has ~5% markup)
3. Hardcoded fallback values

Run from the installer or manually:
    python scripts/update_model_pricing.py
"""

